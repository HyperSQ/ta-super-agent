test('DSH 请求在实际 Router 和模型调用之间可追踪，课程间隔离', async t => {
  const store = new Store(':memory:');
  t.after(() => store.close());
  const engine = new TaskEngine(store, new Policy([]));
  engine.createCourse('web:admin', { id: 'math', title: '数分', instructions: '' });
  engine.createCourse('web:admin', { id: 'other', title: '其他', instructions: '' });
  const provider = createServer((req, res) => {
    req.resume();
    res.end(JSON.stringify({ choices: [{ finish_reason: 'stop', message: { content: '模拟模型答复' } }], usage: { total_tokens: 42 } }));
  }).listen(0, '127.0.0.1');
  t.after(() => provider.close());
  await once(provider, 'listening');
  const address = provider.address();
  assert(address && typeof address !== 'string');
  const model = new ChatModel({ baseUrl: 'http://127.0.0.1:' + address.port, apiKey: 'sk-test-credential-value', model: 'fake-model', timeoutMs: 2_000 });
  const runner = new TaskRunner(engine, ({ signal }) => model.complete([{ role: 'user', content: '题目，不含真实数据' }], signal));
  const outbox = new DeliveryOutbox(engine, { async send() { throw new Error('管理渠道不应交付 QQ'); } });
  const runtime = new Runtime(engine, new Router(engine, model), runner, outbox);
  const adminToken = 'activity-test-admin-token';
  const server = createApi(engine, { adminToken, webhookToken: 'activity-test-webhook-token' }).listen(0, '127.0.0.1');
  t.after(() => server.close());
  await once(server, 'listening');
  const apiAddress = server.address();
  assert(apiAddress && typeof apiAddress !== 'string');
  const base = 'http://127.0.0.1:' + apiAddress.port;
  const headers = { authorization: 'Bearer ' + adminToken, 'content-type': 'application/json' };
  const input = await fetch(base + '/v1/dsh/requests', { method: 'POST', headers, body: JSON.stringify({ courseId: 'math', request: '课内问题', requestId: 'some-id' }) });
  assert.equal(input.status, 202);
  const receipt = await input.json();
  for (let i = 0; i < 10; i++) {
    runtime.tick();
    await runner.idle();
    if (store.tasks()[0]?.status === 'completed') break;
    await new Promise(resolve => setImmediate(resolve));
  }
  const rows = activityPage(store, 'math', Number.MAX_SAFE_INTEGER, receipt.eventId).entries;
  assert.deepEqual(rows.map(row => row.kind).reverse(), ['received', 'route.start', 'task.created', 'route.finish', 'worker.start', 'model.request', 'model.response', 'worker.finish']);
  const req = rows.find(row => row.kind === 'model.request')!;
  const res = rows.find(row => row.kind === 'model.response')!;
  assert.equal(req.runId, res.runId);
  assert.match(JSON.stringify(activityDetail(store, 'math', Number(req.seq))), /题目，不含真实数据/);
  assert.doesNotMatch(JSON.stringify(activityDetail(store, 'math', Number(req.seq))), /sk-test-credential/);
  assert.equal((await fetch(base + '/v1/courses/other/activities/' + res.seq, { headers })).status, 404);
  assert.equal((await fetch(base + '/v1/courses/math/activities')).status, 401);
  assert.equal(store.deliveries().length, 0);
  assert.equal((await (await fetch(base + '/v1/dsh/requests/' + receipt.eventId, { headers })).json()).result, '模拟模型答复');
  await runtime.stop();
});

test('派发预览不入队，确认幂等，Router 拒绝改版并走绑定 QQ 群交付', async t => {
  const store = new Store(':memory:');
  t.after(() => store.close());
  const engine = new TaskEngine(store, new Policy([]));
  engine.createCourse('web:admin', { id: 'math', title: '数分', groupId: '42', instructions: '' });
  const academics = new Academics(engine);
  const info = { courseId: 'math', title: '作业', instructions: 'T2', deadline: '2026-11-30T00:00:00Z', gradingPolicy: '', studentVisible: true };
  const original = academics.saveAssignment('web:admin', info);
  const dsh = new DSH(engine, 'test-secret-value');
  const preview = dsh.preview('math', original.id);
  assert.equal(store.events().length, 0);
  assert.throws(() => dsh.confirm(preview.confirmation.slice(0, -2) + '__'), /无效/);
  const router = new Router(engine, { async complete() { throw new Error('派发不需要模型'); } });
  const stale = dsh.confirm(preview.confirmation);
  assert.equal(dsh.confirm(preview.confirmation).eventId, stale.eventId);
  academics.saveAssignment('web:admin', { ...info, id: original.id, revision: original.revision, instructions: 'T3' });
  const signal = new AbortController().signal;
  await assert.rejects(router.route(store.event(stale.eventId)!, signal), /变更/);
  const receipt = dsh.confirm(dsh.preview('math', original.id).confirmation);
  await router.route(store.event(receipt.eventId)!, signal);
  let sends = 0;
  const outbox = new DeliveryOutbox(engine, { async send(delivery) {
    sends++;
    assert.deepEqual(delivery.channel, { kind: 'qq-group', target: '42' });
    assert.equal(delivery.announcement, true);
    assert.match(delivery.text, /T3/);
    return { externalId: 'mock-qq-1' };
  } }, true);
  assert.equal(dsh.status(receipt.eventId).status, 'pending');
  await outbox.tick();
  await outbox.tick();
  assert.equal(sends, 1);
  assert.equal(dsh.status(receipt.eventId).externalId, 'mock-qq-1');
});
